# Choose match time
def choose_match(matches, stadium):
    print("\n Choose your match time:")

    available_matches = {}

    for key in matches:
        if matches[key]["stadium"] == stadium["name"]:
            available_matches[key] = matches[key]

    for key in available_matches:
        print(
            key + ". " +
            available_matches[key]["date"] +
            " - " +
            available_matches[key]["time"]
        )

    choice = input("Enter your choice: ")

    while choice not in available_matches:
        print(" Invalid choice. Please choose from the available matches.")
        choice = input("Enter your choice: ")

    return available_matches[choice]


