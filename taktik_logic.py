def login():

    attempts = 3

    while attempts > 0:

        try:
            username = input("Enter your username: ")
            password = input("Enter your password: ")

            if username == "admin" and password == "12345":
                print("\nWelcome to Taktik! ⚽")
                return True

            else:
                attempts -= 1

                if attempts > 0:
                    print("Access denied.")
                    print("You have", attempts, "attempt(s) left.\n")
                else:
                    print("Access denied.")
                    print("Too many failed attempts. System locked.")

        except Exception:
            print("Something went wrong. Please try again.")

    return False

