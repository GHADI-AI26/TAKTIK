def recommend_hotels(stadium):
    """
    Return hotel recommendations for the selected stadium.
    Hotels are sorted from closest to farthest.
    """

    if stadium not in hotels:
        return []

    stadium_hotels = hotels[stadium]

    # Sort hotels by distance/time from the stadium
    recommended_hotels = sorted(
        stadium_hotels,
        key=lambda hotel: hotel["minutes"]
    )

    return recommended_hotels

